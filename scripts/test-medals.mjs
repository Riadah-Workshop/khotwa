import assert from 'node:assert/strict';
import ts from 'typescript';
import fs from 'node:fs';
const source=ts.transpileModule(fs.readFileSync('lib/student-medal.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {medalCandidates}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const s={id:'a',name:'طالب',grade:'الرابع',classroom:'أ',active:1};
const round={id:'r',date:'2026-11-02',grade:s.grade,classroom:s.classroom,completed:1};
const record={studentId:'a',roundId:'r',date:round.date,status:'present',updatedAt:'1'};
const run=(records=[record],rounds=[round],cases=[],students=[s])=>medalCandidates(students,records,rounds,cases,'2026-11-01','2026-11-03');
assert.equal(run()[0].eligible,true);
assert.equal(run([])[0].eligible,false);
assert.equal(run([{...record,status:'absent'}])[0].eligible,false);
assert.equal(run([{...record,status:'unmarked'}])[0].eligible,false);
assert.equal(run([{...record,status:'late'}])[0].eligible,false);
assert.equal(run([record],[{...round,completed:0}])[0].eligible,false);
assert.equal(run([record],[round,{...round,id:'r2',date:'2026-11-03'}])[0].eligible,false);
const bad={studentId:'a',type:'المخالفات السلوكية',occurredAt:'2026-11-02T12:00:00Z'};
assert.equal(run([record],[round],[bad])[0].eligible,false);
assert.equal(run([record],[round],[{...bad,deletedAt:'now'}])[0].eligible,true);
assert.equal(run([record],[round],[{...bad,type:'الاستئذان'},{...bad,type:'التأخر الصباحي'},{...bad,type:'التواصل مع ولي الأمر'}])[0].eligible,false);
assert.equal(run([record],[round],[{...bad,occurredAt:'2026-10-31T22:30:00Z'}])[0].eligible,false,'Riyadh date boundary');
assert.equal(run([record],[round],[{...bad,occurredAt:'2026-10-30T12:00:00Z'}])[0].eligible,true);
assert.equal(run([record,{...record,status:'absent',updatedAt:'0'}])[0].eligible,true,'latest record wins');
assert.equal(run([record,{...record,status:'absent',updatedAt:'2'}])[0].eligible,false);
assert.equal(run([record],[round],[],[{...s,active:0}]).length,0);
assert.deepEqual(medalCandidates([s],[record],[round],[],'2026-11-03','2026-11-01'),[]);
console.log('PASS: medal qualification, missing records, corrected attendance, behavior, archived students, Riyadh dates.');

for(const type of ['الاستئذان','التأخر الصباحي','التأخر عن دخول الحصة','الملاحظات','التواصل مع ولي الأمر','السلوك الإيجابي','الوقائع والإسعافات'])assert.equal(run([record],[round],[{...bad,type}])[0].eligible,false,type);
