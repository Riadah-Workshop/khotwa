import assert from 'node:assert/strict';
import {trustedBrowserOrigin} from '../lib/request-origin.ts';
const origins='https://khotwa-ksa.com,https://www.khotwa-ksa.com';
const request=(url,origin,fetchSite)=>new Request(url,{method:'POST',headers:{...(origin?{origin}:{}),...(fetchSite?{'sec-fetch-site':fetchSite}:{})}});
const internal='http://127.0.0.1:3000/api/data';
assert.equal(trustedBrowserOrigin(request(internal,'https://khotwa-ksa.com','same-site'),origins),true);
assert.equal(trustedBrowserOrigin(request(internal,'https://www.khotwa-ksa.com','same-site'),origins),true);
assert.equal(trustedBrowserOrigin(request('https://khotwa-ksa.com/api/data','https://khotwa-ksa.com','same-origin'),undefined),true);
assert.equal(trustedBrowserOrigin(request(internal,'https://evil.example','same-site'),origins),false);
assert.equal(trustedBrowserOrigin(request(internal,'https://sub.khotwa-ksa.com','same-site'),origins),false);
assert.equal(trustedBrowserOrigin(request(internal,'https://khotwa-ksa.com.evil.example','same-site'),origins),false);
assert.equal(trustedBrowserOrigin(request(internal,'https://khotwa-ksa.com/path','same-site'),origins),false);
assert.equal(trustedBrowserOrigin(request(internal,'null','same-site'),origins),false);
assert.equal(trustedBrowserOrigin(request(internal,'http://khotwa-ksa.com','same-site'),origins),false);
assert.equal(trustedBrowserOrigin(request(internal,'https://khotwa-ksa.com','cross-site'),origins),false);
assert.equal(trustedBrowserOrigin(request(internal,undefined,'same-origin'),origins),false);
assert.equal(trustedBrowserOrigin(request(internal,undefined,'same-origin'),origins,true),true);
assert.equal(trustedBrowserOrigin(request(internal,undefined,'cross-site'),origins,true),false);
assert.equal(trustedBrowserOrigin(request(internal,'https://khotwa-ksa.com','same-site'),'https://other.example'),false);
console.log('Origin-policy tests passed: exact HTTPS allowlist, internal proxy URL, cross-site rejection and prior optional-Origin semantics.');
